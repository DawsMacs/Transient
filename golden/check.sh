# Compares what this platform's build of Transient produces with the committed goldens (see golden/README.md).
#
#   golden/check.sh            generate the outputs GOLDEN_RUNS times (default 3), require the runs to agree with each other,
#                              then compare the first run with the goldens
#   golden/check.sh update     regenerate the goldens from this machine (do this deliberately, and say why in the commit)
#
# Exit status: 0 every golden matches; 1 at least one differs; 2 an output could not be generated; 3 the runs on this machine
# disagree with each other (so a mismatch with the goldens would prove nothing).
#
# Set TARGET_FLAG="--target <triple>" to build and run for another target, as the CI matrix does.
# Only deterministic outputs are compared: predictions, replies and the scorecard table. Never timings, memory, joules or warnings.

set -u
cd "$(dirname "$0")/.." || exit 2

RUNS=${GOLDEN_RUNS:-3}
FLAG=${TARGET_FLAG:-}
WORK=target/golden-work
FILES="predictions-exam60-seed1.tsv replies-adapt-seed1.tsv scorecard-seed1.txt"

baby() {
    # shellcheck disable=SC2086
    cargo run --quiet --release --offline $FLAG --bin baby -- "$@"
}

# Write every compared output into directory $1.
generate() {
    local d=$1
    rm -rf "$d"
    mkdir -p "$d"
    baby exam write "$d/exam" --units 60 --seed 1 >/dev/null || return 1
    baby exam run "$d/exam" --no-joules --out "$d/predictions-exam60-seed1.tsv" >/dev/null || return 1
    baby exam adapt-write "$d/adapt" --seed 1 >/dev/null || return 1
    EXAM_NO_JOULES=1 baby exam adapt-run "$d/adapt" --out "$d/replies-adapt-seed1.tsv" >/dev/null || return 1
    # the scorecard minus the one line that carries a timing
    baby school --out "$d/scorecard.school" >"$d/scorecard.raw" || return 1
    grep -v '^taught in' "$d/scorecard.raw" >"$d/scorecard-seed1.txt"
    local f
    for f in $FILES; do
        tr -d '\r' <"$d/$f" >"$d/$f.lf" && mv "$d/$f.lf" "$d/$f" || return 1
    done
}

mkdir -p "$WORK"
i=1
while [ "$i" -le "$RUNS" ]; do
    echo "run $i of $RUNS ..."
    generate "$WORK/run$i" || { echo "could not generate the outputs (run $i)"; exit 2; }
    i=$((i + 1))
done

# 1. does this machine agree with itself?
i=2
while [ "$i" -le "$RUNS" ]; do
    for f in $FILES; do
        if ! cmp -s "$WORK/run1/$f" "$WORK/run$i/$f"; then
            echo "NOT REPRODUCIBLE on this machine: $f differs between run 1 and run $i."
            echo "A mismatch with the goldens would prove nothing; look for hash-map ordering first (baby/README.md, "Running on other platforms", latent hazards)."
            exit 3
        fi
    done
    i=$((i + 1))
done
echo "the $RUNS runs on this machine are byte-identical to each other"

if [ "${1:-}" = "update" ]; then
    mkdir -p golden
    for f in $FILES; do cp "$WORK/run1/$f" "golden/$f"; done
    {
        echo "Regenerated by golden/check.sh update on $(date -u +%Y-%m-%d)."
        echo "rustc: $(rustc --version)"
        echo "host:  $(uname -srm 2>/dev/null || echo unknown)"
        echo "runs that agreed with each other: $RUNS"
    } >golden/PROVENANCE.txt
    echo "goldens updated from this machine:"
    cat golden/PROVENANCE.txt
    exit 0
fi

# 2. does it agree with the goldens?
status=0
for f in $FILES; do
    tr -d '\r' <"golden/$f" >"$WORK/want.tmp"
    if cmp -s "$WORK/want.tmp" "$WORK/run1/$f"; then
        echo "golden OK:      $f"
    else
        n=$(diff "$WORK/want.tmp" "$WORK/run1/$f" | grep -c '^>')
        echo "golden DIFFERS: $f ($n lines differ)"
        diff "$WORK/want.tmp" "$WORK/run1/$f" | head -10
        status=1
    fi
done
exit $status
