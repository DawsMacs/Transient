# Compares what this build of Novice produces with the committed goldens (see novice/golden/README.md).
#
#   novice/golden/check.sh            generate the outputs GOLDEN_RUNS times (default 2), require the runs to agree with each other,
#                                     then compare the first run with the goldens
#   novice/golden/check.sh update     regenerate the goldens from this machine (deliberately, and say why in the commit)
#
# Exit status: 0 every golden matches; 1 at least one differs; 2 an output could not be generated; 3 the runs on this machine disagree
# with each other (so a mismatch with the goldens would prove nothing).
#
# What is compared is deterministic: Novice's replies, the judge's table, and Novice's own account of its work (kinds explained, the programs,
# counted evaluations). Never timings, memory or joules. NOVICE_BIN and BABY_BIN may name binaries that are already built.

set -u
cd "$(dirname "$0")/../.." || exit 2

RUNS=${GOLDEN_RUNS:-2}
WORK=target/novice-golden-work
GOLDEN=novice/golden
# the adaptive exam of the entry tier, and the seven sets of hidden worlds (all development sets now), seed 1 each
EXAMS="static60-seed1 adapt-seed1 hidden-a-seed1 hidden-b-seed1 hidden-c-seed1 hidden-d-seed1 hidden-e-seed1 hidden-f-seed1 hidden-g-seed1"

if [ -z "${NOVICE_BIN:-}" ]; then
    (cd novice && cargo build --quiet --release --offline) || exit 2
    NOVICE_BIN=$PWD/novice/target/release/novice
fi
if [ -z "${BABY_BIN:-}" ]; then
    cargo build --quiet --release --offline --bin baby || exit 2
    BABY_BIN=$PWD/target/release/baby
fi
export NOVICE_BIN

# Judge the adaptive exam in $1 and write the golden $2: the judge's table, Novice's account of its work, and every reply.
adaptive() {
    local dir=$1 out=$2
    OUT=$out.replies ERR=$out.work EXAM_NO_JOULES=1 "$BABY_BIN" exam adapt-drive "$dir" \
        bash -c 'exec 3>"$OUT"; "$NOVICE_BIN" serve 2>"$ERR" | tee /dev/fd/3' >"$out.judge" || return 1
    {
        echo "== judge =="
        cat "$out.judge"
        echo "== work =="
        cat "$out.work"
        echo "== replies =="
        cat "$out.replies"
    } >"$out" && rm -f "$out.judge" "$out.work" "$out.replies"
}

# Write every compared output into directory $1.
generate() {
    local d=$1 e
    rm -rf "$d"
    mkdir -p "$d/exams"
    for e in $EXAMS; do
        case $e in
            static60-seed1)
                "$BABY_BIN" exam write "$d/exams/$e" --units 60 --seed 1 >/dev/null || return 1
                "$NOVICE_BIN" static "$d/exams/$e" --out "$d/$e.pred" || return 1
                { echo "== judge =="; "$BABY_BIN" exam score "$d/exams/$e" "$d/$e.pred"; echo "== predictions =="; cat "$d/$e.pred"; } >"$d/$e" || return 1
                rm -f "$d/$e.pred"
                ;;
            adapt-seed1)
                "$BABY_BIN" exam adapt-write "$d/exams/$e" --seed 1 >/dev/null || return 1
                adaptive "$d/exams/$e" "$d/$e" || return 1
                ;;
            hidden-*)
                local letter=${e#hidden-}; letter=${letter%%-*}
                local script=tools/hidden_worlds_$letter.py
                [ "$letter" = a ] && script=tools/hidden_worlds.py
                python3 "$script" "$d/exams/$e" --seed 1 >/dev/null || return 1
                adaptive "$d/exams/$e" "$d/$e" || return 1
                ;;
        esac
        tr -d '\r' <"$d/$e" >"$d/$e.lf" && mv "$d/$e.lf" "$d/$e" || return 1
    done
    rm -rf "$d/exams"
}

mkdir -p "$WORK"
i=1
while [ "$i" -le "$RUNS" ]; do
    echo "run $i of $RUNS ..."
    generate "$WORK/run$i" || { echo "could not generate the outputs (run $i)"; exit 2; }
    i=$((i + 1))
done

# 1. does this machine agree with itself?
i=2
while [ "$i" -le "$RUNS" ]; do
    for e in $EXAMS; do
        if ! cmp -s "$WORK/run1/$e" "$WORK/run$i/$e"; then
            echo "NOT REPRODUCIBLE on this machine: $e differs between run 1 and run $i."
            echo "A mismatch with the goldens would prove nothing; look for hash-map ordering first."
            exit 3
        fi
    done
    i=$((i + 1))
done
echo "the $RUNS runs on this machine are byte-identical to each other"

if [ "${1:-}" = "update" ]; then
    mkdir -p "$GOLDEN"
    for e in $EXAMS; do cp "$WORK/run1/$e" "$GOLDEN/$e.txt"; done
    {
        echo "Regenerated by novice/golden/check.sh update on $(date -u +%Y-%m-%d)."
        echo "rustc: $(rustc --version)"
        echo "host:  $(uname -srm 2>/dev/null || echo unknown)"
        echo "runs that agreed with each other: $RUNS"
    } >"$GOLDEN/PROVENANCE.txt"
    echo "goldens updated from this machine:"
    cat "$GOLDEN/PROVENANCE.txt"
    exit 0
fi

# 2. does it agree with the goldens?
status=0
for e in $EXAMS; do
    if [ ! -f "$GOLDEN/$e.txt" ]; then
        echo "MISSING golden: $GOLDEN/$e.txt (run novice/golden/check.sh update)"
        status=1
    elif cmp -s "$WORK/run1/$e" "$GOLDEN/$e.txt"; then
        echo "OK       $e"
    else
        echo "DIFFERS  $e"
        diff "$GOLDEN/$e.txt" "$WORK/run1/$e" | head -20
        status=1
    fi
done
if [ "$status" -eq 0 ]; then
    echo "every golden matches"
else
    echo "at least one golden differs: do not adopt the new output; either it is a platform difference or a logic change that was not followed by an update"
fi
exit "$status"
